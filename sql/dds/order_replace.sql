-- Замена одного дня DDS готовой партицией донора.
-- Повтор при неизменном источнике сохраняет деловые данные без дублей.
--
-- ON CLUSTER выполняет замену на обеих нодах по локальным таблицам.
-- Донор и цель имеют одинаковую структуру и ключ шардирования
-- (sql/ddl/45-dds-tables.sql); REPLACE PARTITION строки не перераспределяет.
-- Замена атомарна внутри шарда. Между заменами на разных шардах читатель
-- может увидеть часть прежних и часть новых данных. После сбоя этот период
-- длится до успешного повтора. Пустая партиция донора удаляет день из цели.
--
-- День подставляет Jinja: параметры ClickHouse в ALTER ... PARTITION
-- не поддерживаются в закрепленной версии 26.3. Значение получено
-- из результата order_scope.sql; замер — docs/architecture/storage.md.

ALTER TABLE dds.order_rep ON CLUSTER clickstream_cluster
REPLACE PARTITION '{{ params.day }}' FROM dds.order_stage_rep;
