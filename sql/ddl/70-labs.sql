CREATE VIEW dm.events_enriched_v
ON CLUSTER clickstream_cluster AS
SELECT
	event_date,
	event_time,
	toHour(event_time) AS event_hour,
	client_id,
	event_id,
	event_type,
	url,
	concat('/', splitByChar('?', arrayStringConcat(arraySlice(splitByChar('/', splitByString('://', url)[2]), 2), '/'))[1]) AS page_path,
	referer,
	splitByChar('/', splitByString('://', referer)[2])[1] AS referer_host,
	title,
	utm_source,
	utm_medium,
	utm_campaign,
	utm_content,
	utm_term,
	device_category,
	browser,
	operating_system,
	region_country,
	region_city,
	product_id,
	product_name,
	product_category,
	product_price,
	product_quantity,
	product_event_type,
	purchase_id,
	purchase_revenue,
	purchase_coupon
FROM dds.event_v;